    console.debug("[RaisedPanel_PC] navigate:", {
      path: "/flooring/catalog",
      query: { type: "raised", raised: category },
    });
    router.push({
      path: "/flooring/catalog",
      query: { type: "raised", raised: category },
    });
    ENABLE_SCROLL();
    isLoading.value = false;
  }, 1000);
}
